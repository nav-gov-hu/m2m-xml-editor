create table xsd_validation_request (
    id number(19) generated by default as identity primary key,
    request_id varchar2(100 char) not null,
    xml_file_id number(19) not null,
    xml_file_session_id varchar2(100 char),
    job_id varchar2(100 char) not null,
    xsd_path varchar2(2000 char) not null,
    status varchar2(50 char) not null,
    result_status varchar2(50 char),
    error_count number(10) default 0 not null,
    warning_count number(10) default 0 not null,
    info_count number(10) default 0 not null,
    max_errors_reached number(1) default 0 not null,
    technical_error_message clob,
    started_at timestamp,
    finished_at timestamp,
    created_at timestamp default current_timestamp not null,
    created_by varchar2(255 char),
    updated_at timestamp,
    updated_by varchar2(255 char),
    constraint uk_xsd_validation_request_id unique (request_id),
    constraint fk_xsd_validation_request_file foreign key (xml_file_id) references xml_file(id)
);

create index idx_xsd_validation_request_file on xsd_validation_request(xml_file_id);
create index idx_xsd_validation_request_job on xsd_validation_request(job_id);
create index idx_xsd_validation_request_status on xsd_validation_request(status);
create index idx_xsd_validation_request_created_at on xsd_validation_request(created_at);

create table xsd_validation_error (
    id number(19) generated by default as identity primary key,
    request_entity_id number(19) not null,
    request_id varchar2(100 char) not null,
    xml_file_id number(19) not null,
    severity varchar2(32 char) not null,
    error_code varchar2(100 char),
    error_message clob,
    line_number number(10),
    column_number number(10),
    path clob,
    created_at timestamp default current_timestamp not null,
    created_by varchar2(255 char),
    constraint fk_xsd_validation_error_request foreign key (request_entity_id) references xsd_validation_request(id),
    constraint fk_xsd_validation_error_file foreign key (xml_file_id) references xml_file(id)
);

create index idx_xsd_validation_error_request on xsd_validation_error(request_id);
create index idx_xsd_validation_error_file on xsd_validation_error(xml_file_id);
create index idx_xsd_validation_error_severity on xsd_validation_error(severity);
