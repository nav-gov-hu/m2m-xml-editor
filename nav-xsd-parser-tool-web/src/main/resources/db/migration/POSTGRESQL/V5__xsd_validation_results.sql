create table if not exists xsd_validation_request (
    id bigint generated by default as identity primary key,
    request_id varchar(100) not null,
    xml_file_id bigint not null,
    xml_file_session_id varchar(100),
    job_id varchar(100) not null,
    xsd_path varchar(2000) not null,
    status varchar(50) not null,
    result_status varchar(50),
    error_count integer not null default 0,
    warning_count integer not null default 0,
    info_count integer not null default 0,
    max_errors_reached boolean not null default false,
    technical_error_message text,
    started_at timestamp,
    finished_at timestamp,
    created_at timestamp not null default current_timestamp,
    created_by varchar(255),
    updated_at timestamp,
    updated_by varchar(255),
    constraint uk_xsd_validation_request_id unique (request_id),
    constraint fk_xsd_validation_request_file foreign key (xml_file_id) references xml_file(id)
);

create index if not exists idx_xsd_validation_request_file on xsd_validation_request(xml_file_id);
create index if not exists idx_xsd_validation_request_job on xsd_validation_request(job_id);
create index if not exists idx_xsd_validation_request_status on xsd_validation_request(status);
create index if not exists idx_xsd_validation_request_created_at on xsd_validation_request(created_at);

create table if not exists xsd_validation_error (
    id bigint generated by default as identity primary key,
    request_entity_id bigint not null,
    request_id varchar(100) not null,
    xml_file_id bigint not null,
    severity varchar(32) not null,
    error_code varchar(100),
    error_message text,
    line_number integer,
    column_number integer,
    path text,
    created_at timestamp not null default current_timestamp,
    created_by varchar(255),
    constraint fk_xsd_validation_error_request foreign key (request_entity_id) references xsd_validation_request(id),
    constraint fk_xsd_validation_error_file foreign key (xml_file_id) references xml_file(id)
);

create index if not exists idx_xsd_validation_error_request on xsd_validation_error(request_id);
create index if not exists idx_xsd_validation_error_file on xsd_validation_error(xml_file_id);
create index if not exists idx_xsd_validation_error_severity on xsd_validation_error(severity);
